#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Pentanihon Web Manifest Builder
Quét tất cả các tập truyện trong thư mục story/ và tạo file JSON + JS manifest
để trang chủ Vercel (index.html) và trình đọc (reader.html) luôn tự động cập nhật
mỗi khi có tập truyện mới được xuất bản!
"""
import os
import glob
import re
import json

WORKSPACE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORY_DIR = os.path.join(WORKSPACE_DIR, 'story')


def clean_vi_title(raw):
    s = re.sub(r'^##\s*', '', raw).strip()
    if s.startswith('*') and s.endswith('*'):
        s = s[1:-1].strip()
    if s.startswith('(') and s.endswith(')'):
        s = s[1:-1].strip()
    return s


def parse_story_file(filepath):
    rel_path = os.path.relpath(filepath, WORKSPACE_DIR).replace('\\', '/')
    basename = os.path.basename(filepath)
    ep_match = re.search(r'tap-(\d+)', basename)
    ep_num = int(ep_match.group(1)) if ep_match else 0

    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    lines = content.splitlines()
    title_jp = basename
    title_vi = ""

    for line in lines[:5]:
        s = line.strip()
        if s.startswith('# ') and not title_vi:
            title_jp = re.sub(r'^#\s*🌸?\s*(Tập\s*\d+:\s*)?', '', s).strip()
        elif s.startswith('## '):
            title_vi = clean_vi_title(s)

    # Trích xuất câu nói thực chiến nếu có (hỗ trợ cả blockquote > ### ...)
    quote_jp = ""
    quote_vi = ""
    q_match = re.search(
        r'>?\s*###\s*\*\*(「[^」]+」)\*\*\s*(?:\n>\s*)+\*\(([^)]+)\)\*',
        content
    )
    if q_match:
        quote_jp = q_match.group(1).strip()
        quote_vi = q_match.group(2).strip()

    return {
        "ep": ep_num,
        "file": rel_path,
        "filename": basename,
        "title_jp": title_jp,
        "title_vi": title_vi,
        "quote_jp": quote_jp,
        "quote_vi": quote_vi,
    }


def build_manifest():
    pattern = os.path.join(STORY_DIR, 'series-*.md')
    files = sorted(glob.glob(pattern))
    stories = [parse_story_file(f) for f in files]
    # Sắp xếp mới nhất lên đầu
    stories.sort(key=lambda x: x['ep'], reverse=True)

    # Quét thêm oneshots
    oneshot_files = sorted(glob.glob(os.path.join(STORY_DIR, 'oneshots', '*.md')))
    oneshots = []
    for f in oneshot_files:
        rel_path = os.path.relpath(f, WORKSPACE_DIR).replace('\\', '/')
        with open(f, 'r', encoding='utf-8') as fp:
            first_line = fp.readline().strip()
        title = re.sub(r'^#\s*🌸?\s*', '', first_line).strip()
        oneshots.append({
            "file": rel_path,
            "title": title or os.path.basename(f)
        })

    # Tìm câu nói thực chiến mới nhất
    latest_quote = None
    for st in stories:
        if st.get("quote_jp"):
            latest_quote = {
                "ep": st["ep"],
                "file": st["file"],
                "quote_jp": st["quote_jp"],
                "quote_vi": st["quote_vi"]
            }
            break

    manifest = {
        "total_episodes": len(stories),
        "latest_episode": stories[0] if stories else None,
        "latest_quote": latest_quote,
        "episodes": stories,
        "oneshots": oneshots
    }

    json_path = os.path.join(STORY_DIR, 'stories.json')
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    js_path = os.path.join(STORY_DIR, 'stories-data.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("// Auto-generated by build_web_manifest.py\n")
        f.write("window.PENTANIHON_MANIFEST = ")
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"✅ Built web manifest: {len(stories)} series episodes, {len(oneshots)} oneshots.")
    return manifest


if __name__ == '__main__':
    build_manifest()
