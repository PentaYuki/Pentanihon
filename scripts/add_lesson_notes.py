def block(title, lines, extra=''):
    body = '\n'.join(f'- {l}' for l in lines)
    return f"""

---

{START}
## 📝 Ghi Chú Của Chị — {title}

{body}
{extra}
### ✏️ Ghi chú riêng của em
> *(Em ghi lại câu mình hay sai, từ khó nhớ hoặc câu ví dụ tự đặt ở đây nhé)*
>
> - 
{END}
"""

def check_block(items):
    out = '\n### 🔎 Tự kiểm tra nhanh (che đáp án rồi làm thử)\n'
    for i, (q, a) in enumerate(items, 1):
        out += f'{i}. {q}\n   <details><summary>Xem đáp án</summary>{a}</details>\n'
    return out

def write(path, text):
    with open(path, encoding='utf-8') as f:
        s = f.read()
    if START in s:
        s = s[:s.index(START)].rstrip()
        if s.endswith('---'):
            s = s[:-3].rstrip()
    else:
        s = s.rstrip()
    with open(path, 'w', encoding='utf-8') as f:
        f.write(s + text)

